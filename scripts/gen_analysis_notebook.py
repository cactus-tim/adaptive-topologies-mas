"""Generate notebooks/analysis_template.ipynb programmatically.

Usage
-----
    python scripts/gen_analysis_notebook.py           # write/overwrite notebooks/analysis_template.ipynb
    python scripts/gen_analysis_notebook.py --check   # exit 1 if committed file differs from generated

The notebook has four RQ sections:
  - RQ1: Pareto frontier, topology x task heatmap, phase timeline
  - RQ2: All 7 G11 derived-metrics + 5 plot functions
  - RQ3: Placeholder (out-of-scope for M13)
  - RQ4: Cognitive-load boxplot, oracle vs router
"""

