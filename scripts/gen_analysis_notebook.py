def generate_notebook() -> nbformat.NotebookNode:
    """Build and return a new NotebookNode for the ATM analysis template.

    The notebook is structured as:
      - Preamble / setup
      - RQ1 section
      - RQ2 section (all 7 metric symbols + 5 plot functions)
      - RQ3 section (placeholder)
      - RQ4 section

    Returns:
        A fully populated nbformat 4 NotebookNode that passes nbformat.validate().
    """
    cells: list[nbformat.NotebookNode] = []
    cells.extend(_setup_cells())
    cells.extend(_rq1_cells())
    cells.extend(_rq2_cells())
    cells.extend(_rq3_cells())
    cells.extend(_rq4_cells())

    nb = nbv4.new_notebook(cells=cells)  # type: ignore[no-untyped-call]

    # Set kernel metadata so nbformat.validate() is satisfied
    nb.metadata["kernelspec"] = {
        "display_name": "Python 3",
        "language": "python",
        "name": "python3",
    }
    nb.metadata["language_info"] = {
        "name": "python",
        "version": "3.11.0",
    }

    return nb  # type: ignore[no-any-return]


# ---------------------------------------------------------------------------
# CLI entry point
# ---------------------------------------------------------------------------


def _write_notebook(nb: nbformat.NotebookNode, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as fh:
        nbformat.write(nb, fh)  # type: ignore[no-untyped-call]


def _cell_sources(nb: nbformat.NotebookNode) -> list[str]:
    return [cell["source"] for cell in nb.cells]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate notebooks/analysis_template.ipynb")
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit 1 if the committed notebook differs from the generated one.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=_OUTPUT_PATH,
        help="Output path (default: notebooks/analysis_template.ipynb)",
    )
    args = parser.parse_args(argv)

    nb = generate_notebook()
    nbformat.validate(nb)

    if args.check:
        committed_path: Path = args.output
        if not committed_path.exists():
            print(
                f"ERROR: committed notebook not found at {committed_path}",
                file=sys.stderr,
            )
            return 1
        committed_nb = nbformat.read(str(committed_path), as_version=4)  # type: ignore[no-untyped-call]
        if _cell_sources(nb) != _cell_sources(committed_nb):
            print(
                "ERROR: committed notebook differs from generator output.\n"
                f"Re-run `python scripts/gen_analysis_notebook.py` to update {committed_path}",
                file=sys.stderr,
            )
            return 1
        print("OK: committed notebook matches generator output.")
        return 0

    _write_notebook(nb, args.output)
    print(f"Written: {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
